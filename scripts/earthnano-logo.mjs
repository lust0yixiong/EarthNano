/* eslint-disable @typescript-eslint/explicit-function-return-type -- standalone JavaScript asset exporter. */
// Approved v27 vector: shared by renderer, startup particles and platform icon exports.
import { readFile, writeFile } from 'node:fs/promises'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import sharp from 'sharp'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
/** @param {number} size @returns {Promise<Buffer>} */
export const renderEarthNanoLogo = async (size = 512) => {
  const source = await readFile(join(root, 'build/earthnano-logo.svg'))
  return sharp(source, { density: (72 * size) / 512 })
    .png()
    .toBuffer()
}

/** @param {Buffer} png @returns {Promise<number[][]>} */
export const sampleEarthNanoLogo = async (png) => {
  const sample = await sharp(png).resize(96, 96).ensureAlpha().raw().toBuffer()
  const points = []
  for (let y = 3; y < 95; y += 3)
    for (let x = 3; x < 95; x += 3) {
      const i = (y * 96 + x) * 4
      if (sample[i + 3] >= 200) points.push([x, y, sample[i], sample[i + 1], sample[i + 2]])
    }
  return points
}

/** @param {boolean} check @returns {Promise<void>} */
export const exportEarthNanoLogo = async (check = false) => {
  const png = await renderEarthNanoLogo()
  const points = await sampleEarthNanoLogo(png)
  const source =
    '// Generated by scripts/earthnano-logo.mjs from the same transparent renderer mark.\n' +
    'export const EARTHNANO_LOGO_POINTS = [\n' +
    points.map((point) => `  [${point.join(', ')}]`).join(',\n') +
    '\n] as const\n'
  for (const [name, content] of [
    ['src/renderer/src/assets/logo.png', png],
    ['src/renderer/src/assets/logo-dark.png', png],
    ['src/renderer/src/components/earthnano-logo-points.ts', Buffer.from(source)]
  ]) {
    const path = join(root, name)
    if (check) {
      if (!(await readFile(path)).equals(content))
        throw new Error(`${name} is stale; run node scripts/earthnano-logo.mjs`)
    } else await writeFile(path, content)
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.slice(2).some((arg) => arg !== '--check')) throw new Error('Use [--check]')
  await exportEarthNanoLogo(process.argv.includes('--check'))
  console.log('EarthNano renderer marks and startup particle samples are synchronized.')
}
