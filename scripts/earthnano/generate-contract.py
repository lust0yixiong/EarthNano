"""Generate both language types from the deliberately small v1 schema vocabulary."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SCHEMA = json.loads((ROOT / "contracts/execution/schema.json").read_text())


def typename(schema, language):
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[1]
    if "const" in schema:
        values = [schema["const"]]
    elif "enum" in schema:
        values = schema["enum"]
    else:
        values = None
    if values is not None:
        literals = [json.dumps(value, ensure_ascii=False) for value in values]
        return " | ".join(literals) if language == "ts" else f"Literal[{', '.join(literals)}]"
    kind = schema["type"]
    if kind == "array":
        child = typename(schema["items"], language)
        return f"Array<{child}>" if language == "ts" else f"list[{child}]"
    return {
        "ts": {"string": "string", "integer": "number", "boolean": "boolean"},
        "py": {"string": "str", "integer": "int", "boolean": "bool"},
    }[language][kind]


def generate(language):
    lines = (
        ["// Generated by scripts/earthnano/generate-contract.py. Do not edit.", ""]
        if language == "ts"
        else ['"""Generated by scripts/earthnano/generate-contract.py. Do not edit."""',
              "from __future__ import annotations",
              "from typing import Literal, NotRequired, TypedDict", ""]
    )
    for name, schema in SCHEMA["definitions"].items():
        if schema.get("type") != "object":
            prefix = f"export type {name} = " if language == "ts" else f"{name} = "
            lines.extend([prefix + typename(schema, language), ""])
            continue
        lines.append(f"export interface {name} {{" if language == "ts" else f"class {name}(TypedDict):")
        for key, child in schema["properties"].items():
            optional = key not in schema["required"]
            value = typename(child, language)
            if language == "ts":
                lines.append(f"  {key}{'?' if optional else ''}: {value}")
            else:
                lines.append(f"    {key}: {'NotRequired[' + value + ']' if optional else value}")
        lines.extend(["}", ""] if language == "ts" else [""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    outputs = {
        "src/shared/earthnano/execution-types.ts": generate("ts"),
        "vendor/harness2/harness2/core/execution_types.py": generate("py"),
        # Keep the installed Python package self-contained; --check catches schema drift.
        "vendor/harness2/harness2/core/execution_schema.json":
            json.dumps(SCHEMA, indent=2) + "\n",
    }
    for filename, content in outputs.items():
        path = ROOT / filename
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f"Generated contract differs: {filename}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)


if __name__ == "__main__":
    main()
